"""
СПІЛЬНЕ · перетворення тексту на числа, якими шукають за змістом.

Пошук по словах знаходить фрагмент лише тоді, коли запит і текст називають річ
однаково. Пошук за змістом працює інакше: і фрагмент, і запит переганяють крізь
одну модель, яка ставить кожному в відповідність триста вісімдесят чотири числа,
а близькість шукають між числами. Тоді «how to find out the type of a value» має
шанс привести до Object.prototype.toString, у якому цих слів немає.

ЧОМУ ONNX, А НЕ TORCH

У практиці модуля 4 та сама робота робиться моделлю e5 на torch. Тут так не
можна, і це вимірювання, а не смак: на цьому диску `import sentence_transformers`
триває 120 секунд навіть на теплому кеші, бо тягне тисячі дрібних файлів torch
через 9p. MCP-сервер, який дві хвилини не відповідає на перший запит, клієнт
вважає мертвим. `fastembed` рахує ті самі числа рушієм ONNX і імпортується за
шість із половиною секунд — одна бібліотека замість тисяч файлів.

ЧОМУ АНГЛІЙСЬКА МОДЕЛЬ

Специфікація англійська, і опис `search_spec` вимагає англійського запиту, тож
багатомовна модель тут платила б розміром ні за що. `bge-small-en-v1.5` дає 384
виміри і займає в кеші 128 МБ; у fastembed є і більша, `bge-base-en-v1.5` на 768
вимірів, і перейти на неї можна змінною PRACTICE_EMBED_MODEL: ім'я моделі
входить в ім'я колекції Qdrant, тож стара колекція від цього не псується.

Модель довантажується сама при першому використанні і лягає в кеш
`~/.cache/huggingface/hub` — 128 МБ на диску. Тому перший запуск після
встановлення довший за наступні.
"""

import os

# Ім'я моделі й короткий ключ для імені колекції. Крапки й косі риски в іменах
# колекцій Qdrant краще не вживати, тому ключ окремий.
MODELS = {
    "bge-small": ("BAAI/bge-small-en-v1.5", 384),
    "bge-base": ("BAAI/bge-base-en-v1.5", 768),
}
MODEL_KEY = os.getenv("PRACTICE_EMBED_MODEL", "bge-small")
if MODEL_KEY not in MODELS:
    raise SystemExit(f"Невідома модель '{MODEL_KEY}'. Доступні: {', '.join(MODELS)}")
MODEL_NAME, DIM = MODELS[MODEL_KEY]

# Скільки текстів модель бере за раз. Менша пачка тут швидша за типову (256), і
# причина в вирівнюванні: усі тексти пачки доганяються нулями до найдовшого в
# ній, тож один фрагмент на 1400 символів змушує рахувати зайве за всі 256. На
# цій машині 256 справжніх фрагментів пачками по 32 порахувалися за 163 с проти
# 184 с типовою пачкою.
BATCH = 32

_model = None


def model():
    """Модель, завантажена при першому зверненні і не раніше.

    Ліниво — бо сервер має відповісти клієнтові одразу після запуску, а
    завантаження займає секунди й може ще й тягнути файли з мережі. До першого
    пошуку за змістом ця функція не викликається взагалі.
    """
    global _model
    if _model is None:
        try:
            from fastembed import TextEmbedding
        except ModuleNotFoundError as exc:
            # Помилку не гасимо і на SystemExit не міняємо: сервер знань ловить
            # саме Exception і без векторів працює по словах далі. Тут лише
            # дописуємо до неї те, чого бракує читачеві, — команду.
            raise ModuleNotFoundError(
                "немає fastembed, а без нього вектори нема чим рахувати; "
                "постав: .venv/bin/python -m pip install fastembed") from exc
        _model = TextEmbedding(model_name=MODEL_NAME)
    return _model


def loaded() -> bool:
    """Чи модель уже в пам'яті. Потрібно лише для чесної діагностики."""
    return _model is not None


def embed_passages(texts: list[str]) -> list[list[float]]:
    """Числа для фрагментів. Модель bge просить, щоб документи йшли без
    префікса, а запити — з префіксом; fastembed знає це сам."""
    return [v.tolist() for v in model().embed(texts, batch_size=BATCH)]


def embed_query(text: str) -> list[float]:
    """Числа для запиту користувача."""
    return next(iter(model().query_embed([text]))).tolist()
