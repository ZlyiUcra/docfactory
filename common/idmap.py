"""
СПІЛЬНЕ · унікальні ідентифікатори фрагментів.

`corpus.Passage.pid` майже завжди унікальний, але не завжди: на повній
специфікації в розділі 16-ecmascript-language-scripts-and-modules два рядки
кроків алгоритму, «1 ( D )» і «1 ( B )», розбір приймає за заголовки розділу з
номером 1, і два різні фрагменти дістають однаковий pid. Якби ідентифікатори
роздавав словник, другий тихо затер би перший: пошук показав би його
ідентифікатор, а читання повернуло б чужий текст.

Тому ідентифікатори роздаються тут, в одному місці, і повторному дописується
«~2». Одне місце важливе: сервер віддає ці ідентифікатори клієнтові, а заливання
в Qdrant кладе їх у payload, і збігтися вони мусять до символа.
"""

from .corpus import Passage


def assign_ids(passages: list[Passage]) -> tuple[dict[str, Passage],
                                                 dict[Passage, str]]:
    """Повертає дві мапи: ідентифікатор → фрагмент і фрагмент → ідентифікатор."""
    by_id: dict[str, Passage] = {}
    uid_of: dict[Passage, str] = {}
    for p in passages:
        uid = p.pid
        n = 2
        while uid in by_id:
            uid = f"{p.pid}~{n}"
            n += 1
        by_id[uid] = p
        uid_of[p] = uid
    return by_id, uid_of
